// 界面的层序：一条从「背景」到「盖住整屏」的阶梯。
//
// 起因是那几张被压住的截图。Godot 的规矩是「同级子节点里 ZIndex 大的在上；
// ZIndex 相同就谁先 AddChild 谁在下」——于是每一处 `ZIndex = 1` 都在跟另一个
// `ZIndex = 1` 比谁先被加进去，而这件事读代码读不出来，只在截图上看得出来。
//
// 上一轮修的就是这样一处：Arena（满屏铺的墙与地砖）和两块条带（HudBand）都是默认的 0，
// 谁先加谁在下——Arena 先加，于是敌人卡的上半截和屏幕最下方那条全是墙色。
// 当时给条带写了 `ZIndex = 1`，但那个 1 的意思是「比 Arena 大一点」，
// 不是「面板该在这一层」。下一次再来一块新东西，同一道题要再做一遍。
//
// 所以把这些数收进来，并且让这些数字不再作为字面量出现在场景代码里：
// 要压住谁，先说出「我是哪一层」。同一层之内仍然按添加顺序叠——
// 同一层本来就该是一起画的东西。
//
// 这是 ZIndex，不是输入事件的先后：点击谁先拿到由树的顺序与 MouseFilter 决定
// （弹窗靠 `MouseFilter.Stop` 拦住下面，不靠这个数）。
namespace AbyssEcho.UI;

public enum StageOrder
{
    /// <summary>整屏的底：纯色场、氛围层、舞台背景（Arena 的墙与地砖）</summary>
    Backdrop = 0,

    /// <summary>面板：敌人卡、行动条，以及它们的条带底与卡面。**必须在 Backdrop 之上**——
    /// 上一轮那个「卡面其实是墙色」的 bug，答案就是这句话</summary>
    Panel = 1,

    /// <summary>
    /// 面板**里面装的东西**：HUD 的字与进度条、行动条里的按钮行。
    ///
    /// 面板的「底」（`HudBand`）和它承载的内容是两层，这一层说的是上面那层。
    /// 少了这一档，「内容在哪一层」就退化成「谁先 AddChild」——地图 HUD 的文字与两条
    /// 进度条因此被自己的条带盖住了一整轮：「字一直在画，只是被垫在上面了」。
    /// </summary>
    PanelContent = 2,

    /// <summary>舞台上的人物，以及承载它们的那一层容器本身。夹在上下两块面板中间</summary>
    Stage = 3,

    /// <summary>飘字（伤害数字）：盖在人物上，但不许盖过面板</summary>
    Float = 5,

    /// <summary>粒子与命中特效：比飘字再高一档，一次爆炸能盖住半个舞台</summary>
    Fx = 6,

    /// <summary>组合战里的小卡：属于面板，但要压住舞台上的一切</summary>
    EnemyChip = 20,

    /// <summary>地图上「你在这儿」那一块。
    ///
    /// 它和 `Float`（飘字）本来是同一个数 5——两件事撞在同一个层号上，
    /// 「谁在上」就退化成「谁先 AddChild」，正是这一轮要消灭的那种巧合。
    /// 地图与战斗不在同一棵树里，撞了也没画面事故，但判据说得对：
    /// 一个只有在跟别人比大小时才有意义的数字，不该两个人共用。
    /// 挪到 `Float` 与 `Fx` 之间：飘字本该盖住地图上的玩家（伤害数字要在人上面）。</summary>
    Actor = 8,

    /// <summary>地图上那块图例（横带或竖带，看宽度）：浮在网格之上的说明牌</summary>
    Legend = 40,

    /// <summary>浮动提示：它要压住网格与图例，否则「那边没有路」就白说了</summary>
    Toast = 90,

    /// <summary>
    /// 战斗这一整块的子树根。
    ///
    /// 战斗是**挂在地图场景下面**的：地图的 HUD 条带占着 `Panel`、HUD 的内容占着
    /// `PanelContent`。两棵树，ZIndex 却是在同一块画布上比的——于是战斗自己的
    /// 行动条（`Panel` = 1）反倒压在地图 HUD 的内容（2）上面。
    /// 一条「子树根」把战斗抬出地图的地盘就够了：抬的是**两层**，
    /// 战斗内部（舞台 3 / 飘字 5 / 粒子 6）的相对顺序一个都没动。
    ///
    /// 取 30 而不是 10：飘字、粒子的层号是**子树内的绝对数**，而 `ZIndex` 是全局的——
    /// 把它设成 10 等于把 5/6 压到地图图例（40）与提示（90）下面，伤害数字会被图例吃掉。
    /// 30 落在「图例之上、提示之下」，战斗这一整块都比地图的面板高，同时
    /// 地图底下的浮动提示仍能飘在战斗上面说话。
    /// </summary>
    BattleRoot = 30,

    /// <summary>演出与弹窗：Boss 出场、房间交互面板。这一层出去的东西在收掉之前，别的都不该被看见</summary>
    Overlay = 100,
}

public static class Layers
{
    /// <summary>层号本身。别的 API 真要一个整数时走这里，别在场景里再写一个字面量</summary>
    public static int Of(StageOrder order) => (int)order;

    /// <summary>两层谁在上：只回答「在不在上面」，不回答「差多少」——差多少是手感，不是判据</summary>
    public static bool Above(StageOrder a, StageOrder b) => Of(a) > Of(b);
}
